// Builds docs/product-guide.html: the product guide with the screens from `e2e/guide.spec.ts`
// embedded as data URIs, so the page is one file that opens anywhere. Run with `pnpm guide`.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

const shotsDir = process.env.GUIDE_SHOTS ?? path.join('docs', 'guide-shots');
const out = process.argv[2] ?? path.join('docs', 'product-guide.html');

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
/** Inline markup: **bold** and «…» stay as written; `code` is not used in this text. */
const md = (s) => esc(s).replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');

const missing = [];
function img(name) {
  const file = path.join(shotsDir, `${name}.jpg`);
  if (!existsSync(file)) {
    missing.push(name);
    return '';
  }
  return `data:image/jpeg;base64,${readFileSync(file).toString('base64')}`;
}

/** A row of phone screens; each is [shot, caption]. */
const screens = (items) =>
  `<div class="screens">${items
    .map(
      ([name, caption], i) =>
        `<figure class="screen"><button class="shot" type="button" aria-label="Открыть крупно: ${esc(
          caption.replace(/\*\*/g, ''),
        )}"><img src="${img(name)}" alt="${esc(caption.replace(/\*\*/g, ''))}" width="390" height="844"></button><figcaption><span class="num">${i + 1}</span><span>${md(caption)}</span></figcaption></figure>`,
    )
    .join('')}</div>`;

const steps = (items) => `<ol class="steps">${items.map((s) => `<li>${md(s)}</li>`).join('')}</ol>`;
const bullets = (items) =>
  `<ul class="bullets">${items.map((s) => `<li>${md(s)}</li>`).join('')}</ul>`;
const table = (head, rows) =>
  `<div class="table-wrap"><table><thead><tr>${head.map((h) => `<th>${md(h)}</th>`).join('')}</tr></thead><tbody>${rows
    .map((r) => `<tr>${r.map((c) => `<td>${md(c)}</td>`).join('')}</tr>`)
    .join('')}</tbody></table></div>`;
const rule = (title, body) => `<div class="rule"><h4>${md(title)}</h4>${body}</div>`;
const p = (s) => `<p>${md(s)}</p>`;
const scenario = (title, intro, stepList, shots) =>
  `<div class="scenario"><h3>${md(title)}</h3>${intro ? p(intro) : ''}${stepList ? steps(stepList) : ''}${
    shots ? screens(shots) : ''
  }</div>`;

