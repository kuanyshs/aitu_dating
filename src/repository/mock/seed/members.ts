const DAY = 24;

function paid(months: 1 | 3 | 6 | 12, startedDaysAgo: number) {
  const startsAt = hoursAgo(startedDaysAgo * DAY);
  const endsAt = new Date(
    new Date(startsAt).getTime() + months * 30 * DAY * 3600_000,
  ).toISOString();
  return { tier: 'paid' as const, periodMonths: months, startsAt, endsAt };
}

